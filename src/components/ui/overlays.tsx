/** Confirm-before-acting dialog used by every destructive action in the dashboard. */
export function ConfirmDialog({
  open, onOpenChange, title, description, confirmLabel, cancelLabel, onConfirm, destructive = true, loading,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  title: string;
  description?: React.ReactNode;
  confirmLabel: string;
  cancelLabel: string;
  onConfirm: () => void | Promise<void>;
  destructive?: boolean;
  loading?: boolean;
}) {
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent size="sm">
        <DialogHeader>
          <DialogTitle>{title}</DialogTitle>
          {description ? <DialogDescription>{description}</DialogDescription> : null}
        </DialogHeader>
        <DialogFooter>
          <DialogClose asChild>
            <button className="inline-flex h-10 items-center justify-center rounded-full border border-input bg-card px-5 text-[15px] font-medium hover:bg-secondary">
              {cancelLabel}
            </button>
          </DialogClose>
          <button
            onClick={() => void onConfirm()}
            disabled={loading}
            className={cn(
              'inline-flex h-10 items-center justify-center rounded-full px-5 text-[15px] font-medium text-white disabled:opacity-50',
              destructive ? 'bg-danger hover:bg-danger/90' : 'bg-primary hover:bg-accent/90',
            )}
          >
            {confirmLabel}
          </button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
